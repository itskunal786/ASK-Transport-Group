using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace ASK.Transport.Utils.Helpers;

public static class PdfReportGenerator
{
    public static byte[] GenerateConsignmentBiltyPdf(
        string bookingNumber,
        string fromCity,
        string toCity,
        string customer,
        decimal freightAmount)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(2, Unit.Centimetre);
                page.DefaultTextStyle(x => x.FontSize(11));

                page.Header().Text($"ASK TRANSPORT GROUP - CONSIGNMENT BILTY #{bookingNumber}")
                    .SemiBold().FontSize(16).FontColor(Colors.Blue.Darken2);

                page.Content().PaddingVertical(1, Unit.Centimetre).Column(col =>
                {
                    col.Spacing(10);
                    col.Item().Text($"Consignor: {customer}");
                    col.Item().Text($"Route Corridor: {fromCity} -> {toCity}");
                    col.Item().Text($"Total Freight: INR {freightAmount:N2}");
                    col.Item().Text($"Status: Certified & Digitally Signed");
                });

                page.Footer().AlignCenter().Text(x =>
                {
                    x.Span("Generated by ASK Transport Logistics System | ");
                    x.CurrentPageNumber();
                });
            });
        }).GeneratePdf();
    }
}
